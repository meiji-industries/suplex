import { join } from "node:path";
import { tmpdir } from "node:os";
import { expect, test } from "vitest";
import { nativeBrowser } from "./helpers/native-browser.js";

test.each([1280, 390])("restored task layout, filters, board and work tabs at %ipx", { timeout: 90_000 }, async width => {
  const value = await nativeBrowser(width);
  try {
    const create = (title: string, immediate: boolean) => value.tasks.createTask(value.userId, value.company.id, { projectId: value.project.id, title, description: "Make one small README improvement.", startImmediately: immediate, idempotencyKey: `restore-${title.replaceAll(" ", "-")}` });
    const { task: backlog } = await create("Backlog task", false);
    const { task: delivered } = await create("Improve README", true);
    const store = value.tasks.repository.controls;
    const root = store.claimRoot({ taskId: delivered.id });
    store.bindHarnessSession({ sessionId: root.id, generation: root.generation, nativeSessionId: "ses_private_diagnostics" });
    store.ensureInitialPrompt(root, "Internal execution instructions stay in diagnostics.");
    const turn = store.pendingTurns(root.id)[0];
    if (turn) store.completeRootTurn(turn.id, JSON.stringify({ text: "Updated the README and verified the change." }));
    store.setPullRequest(delivered.id, { repository: "owner/repo", number: 130, url: "https://github.com/owner/repo/pull/130", headSha: "a".repeat(40), state: "merged", mergedAt: new Date().toISOString() });
    store.markDelivered(delivered.id);
    const { page } = value;
    await page.goto(`${value.base}/tasks?company=${value.company.id}`);
    await page.locator("[data-task-row]").filter({ hasText: "Improve README" }).waitFor();
    expect(await page.locator("[data-task-row]").count()).toBe(2);
    await page.getByRole("tab", { name: "Backlog", exact: true }).click();
    expect(await page.locator("[data-task-row]").count()).toBe(1);
    await page.getByRole("tab", { name: "All tasks", exact: true }).click();
    await page.getByLabel("Search tasks", { exact: true }).fill("README");
    expect(await page.locator("[data-task-row]").count()).toBe(1);
    await page.getByLabel("Search tasks", { exact: true }).fill("");
    await page.screenshot({ path: join(tmpdir(), `forge-restored-list-${width}.png`), fullPage: true });
    await page.locator("[data-task-row]").filter({ hasText: "Improve README" }).click();
    await page.getByRole("complementary", { name: "Task properties" }).waitFor();
    for (const name of ["Chat", "Diffs", "Checks", "Other"]) await page.getByRole("tab", { name, exact: true }).waitFor();
    expect(await page.getByText("ses_private_diagnostics", { exact: true }).isVisible()).toBe(false);
    await page.getByText("Updated the README and verified the change.", { exact: true }).waitFor();
    expect(await page.getByText("Internal execution instructions stay in diagnostics.", { exact: true }).isVisible()).toBe(false);
    const main = await page.locator("[data-task-content]").boundingBox();
    const properties = await page.getByRole("complementary", { name: "Task properties" }).boundingBox();
    expect(main).not.toBeNull(); expect(properties).not.toBeNull();
    if (main && properties && width >= 1024) { expect(properties.width).toBe(260); expect(properties.x).toBeGreaterThan(main.x); }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: join(tmpdir(), `forge-restored-detail-${width}.png`), fullPage: true });
    await page.getByRole("tab", { name: "Diffs", exact: true }).click();
    await page.getByText("The worktree is not available.", { exact: true }).waitFor();
    await page.clock.install();
    let diffReads = 0;
    await page.route(`**/api/tasks/${delivered.id}/diff`, route => ++diffReads === 1 ? route.fulfill({ status: 503, json: { error: "Git temporarily busy" } }) : route.fulfill({ json: { available: true, patch: "+Out-of-band README change", truncated: false } }));
    await page.clock.fastForward(5000);
    await page.getByText("Git temporarily busy", { exact: true }).waitFor();
    await page.clock.fastForward(5000);
    await page.getByText("+Out-of-band README change", { exact: true }).waitFor();
    expect(await page.getByText("Git temporarily busy", { exact: true }).isVisible()).toBe(false);
    let checkReads = 0;
    await page.route(`**/api/tasks/${delivered.id}/checks`, route => ++checkReads === 1 ? route.fulfill({ status: 503, json: { error: "GitHub temporarily busy" } }) : route.fulfill({ json: { available: true, runs: [{ name: "Project tests", status: checkReads === 2 ? "pending" : "successful", url: "https://github.com/owner/repo/actions/runs/1" }] } }));
    await page.getByRole("tab", { name: "Checks", exact: true }).click();
    await page.getByText("GitHub temporarily busy", { exact: true }).waitFor();
    await page.clock.fastForward(15000);
    await page.getByRole("link", { name: "Open Project tests", exact: true }).waitFor();
    expect(await page.getByText("GitHub temporarily busy", { exact: true }).isVisible()).toBe(false);
    await page.getByText("Pending", { exact: true }).waitFor();
    await page.clock.fastForward(15000);
    await page.getByText("Passed", { exact: true }).waitFor();
    await page.goto(`${value.base}/board?company=${value.company.id}`);
    await page.getByRole("region", { name: "Backlog", exact: true }).waitFor();
    await page.getByRole("region", { name: "Delivered", exact: true }).waitFor();
    await page.screenshot({ path: join(tmpdir(), `forge-restored-board-${width}.png`), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.getByRole("region", { name: "Backlog", exact: true }).getByRole("link").click();
    await page.getByRole("link", { name: "Open board", exact: true }).waitFor();
    expect(page.url()).toContain(backlog.id);
    expect(value.errors).toEqual([]);
  } finally { await value.close(); }
});
